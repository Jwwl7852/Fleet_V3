export function nytV2Fund(kode, tekst, {
  niveau = REGELNIVEAU.HARD, sti = null, objektId = null,
  objektReference = null, detaljer = null,
} = {}) {
  return {
    kode, tekst, niveau, sti, objektId, objektReference, detaljer,
    reference: `${kode}:${referenceNoegle(objektReference) || objektId || "ukendt"}:${sti || "objekt"}`,
  };
}

export function v2Resultat(fund = [], ekstra = {}) {
  const alle = fund.filter(Boolean);
  return {
    ok: !alle.some((f) => f.niveau === REGELNIVEAU.HARD || f.niveau === REGELNIVEAU.CONTROLLED_EXCEPTION),
    fund: alle,
    ...ekstra,
  };
}
