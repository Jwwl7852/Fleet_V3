import { expect, test } from "@playwright/test";

const collectBrowserErrors = (page) => { const errors = []; page.on("console", (message) => { if (message.type() === "error") errors.push(`console: ${message.text()}`); }); page.on("pageerror", (error) => errors.push(`pageerror: ${error.message}`)); return errors; };

