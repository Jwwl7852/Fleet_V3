test("booking kan annulleres med grund, og mobil viser dagsliste uden vandret overløb", async ({ page }) => {
  const errors = collectBrowserErrors(page);
  await page.setViewportSize({ width: 1672, height: 941 });
  await page.goto("/vaerksted/kalender");
  await page.locator(".calendar-booking").filter({ hasText: "VO-00001" }).first().click();
  await page.getByLabel("Bookingannullering").fill("Ressourcen skal bruges akut andetsteds.");
  await page.getByRole("button", { name: "Annuller booking" }).click();
  await expect(page.locator(".calendar-booking").filter({ hasText: "VO-00001" })).toHaveCount(0);
  await page.goto("/vaerksted/workshop-task-demo-001");
  await expect(page.getByText("Oprettet", { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 1366, height: 768 });
  let widths = await page.evaluate(() => ({ inner: window.innerWidth, scroll: document.documentElement.scrollWidth }));
  expect(widths.scroll).toBe(widths.inner);
  await page.goto("/vaerksted");
  widths = await page.evaluate(() => ({ inner: window.innerWidth, scroll: document.documentElement.scrollWidth }));
  expect(widths.scroll).toBe(widths.inner);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/vaerksted/kalender");
  await expect(page.locator(".calendar-mobile-list")).toBeVisible();
  widths = await page.evaluate(() => ({ inner: window.innerWidth, scroll: document.documentElement.scrollWidth }));
  expect(widths.scroll).toBe(widths.inner);
  await page.goto("/vaerksted/workshop-task-demo-001");
  const taskWidths = await page.evaluate(() => ({ inner: window.innerWidth, scroll: document.documentElement.scrollWidth }));
  expect(taskWidths.scroll).toBe(taskWidths.inner);
  expect(errors).toEqual([]);
});
